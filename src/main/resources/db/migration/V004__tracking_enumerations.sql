-- V004: the two enumerations the legacy API exposes (chapter 08 §2.3 tracking_state,
-- accessory_service; 12b §2.2; ADM-10, API-02). Their ids are the legacy ids; the rows are
-- seeded in V009 and read-only in the M1 UI (ENH-14 manages accessory services later).

CREATE TABLE tracking_state (
    id              smallint     PRIMARY KEY,
    name            varchar(20)  NOT NULL,
    label           varchar(40)  NOT NULL,
    public_title    varchar(60)  NOT NULL,
    step_label      varchar(40),
    sort_order      smallint     NOT NULL,
    CONSTRAINT ck_tracking_state_id CHECK (id BETWEEN 0 AND 5),
    CONSTRAINT uq_tracking_state_name UNIQUE (name),
    CONSTRAINT uq_tracking_state_sort_order UNIQUE (sort_order)
);

COMMENT ON TABLE tracking_state IS
    'The six tracking states of the legacy backend (ids 0-5: NON_GESTITO … CONSEGNATO), seeded exactly from 12b §2.2 (ADM-10) and served unchanged by EP-19 (API-02).';
COMMENT ON COLUMN tracking_state.label IS 'The legacy label ("Presa in carico" …): what the compatibility API returns and the back office shows.';
COMMENT ON COLUMN tracking_state.public_title IS 'The status line of the public tracking page (chapter 06 §5.7).';
COMMENT ON COLUMN tracking_state.step_label IS 'Progress-bar step of the public tracking page; null for NON_GESTITO.';

CREATE TABLE accessory_service (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(60)  NOT NULL,
    label       varchar(120) NOT NULL,
    is_none     boolean      NOT NULL DEFAULT false,
    active      boolean      NOT NULL DEFAULT true,
    sort_order  integer      NOT NULL,
    CONSTRAINT uq_accessory_service_name UNIQUE (name),
    CONSTRAINT uq_accessory_service_sort_order UNIQUE (sort_order)
);

CREATE UNIQUE INDEX ux_accessory_service_single_none ON accessory_service (is_none) WHERE is_none;

COMMENT ON TABLE accessory_service IS
    'Accessory services offered on an order (ids 0-5 are the legacy ids, seeded from 12b §2.2, ADM-10; EP-20 serves them unchanged, API-02). ENH-14 adds rows with the next id.';
COMMENT ON COLUMN accessory_service.name IS 'The legacy constant name (NESSUN_SERVIZIO …), served as "name" by EP-20.';
COMMENT ON COLUMN accessory_service.label IS 'Italian label, served as "label" by EP-20 and shown in the wizard.';
COMMENT ON COLUMN accessory_service.is_none IS
    'True only for id 0 "Nessun servizio accessorio": never offered as a choice; an order without a service has accessory_service_id = NULL.';
